/**
 * Writes real generated boards, and their answers, out for the Dart tests.
 *
 * `npx tsx tools/emit-game-fixtures.ts` from `backend/`.
 *
 * The daily games have their rules written twice — once in `convex/games/*.ts`
 * where a solve is decided, and once in `lib/games/game_rules.dart` where the
 * board decides what to light red. Two implementations of one rule set drift,
 * and the drift is silent in the worst direction: the client sits there looking
 * complete while `submit` rejects it, or paints a legal cell as a mistake.
 *
 * A unit test on either side alone cannot catch that, because each would be
 * checked against its own idea of the rules. So the TypeScript engines emit
 * boards and answers here, and `test/daily_games_test.dart` asserts the Dart
 * mirror accepts exactly the answers the server would and rejects boards one
 * move away from them.
 *
 * Committed rather than generated at test time: the Dart suite must not need a
 * node toolchain to run, and a fixture that regenerates itself would quietly
 * agree with whatever the engine does today.
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";

import * as queens from "../convex/games/queens";
import * as sudoku from "../convex/games/sudoku";
import * as tango from "../convex/games/tango";
import * as zip from "../convex/games/zip";

/** Day keys spread across a year, so the fixtures are not one lucky seed. */
const DAYS = [
  "2026-01-01",
  "2026-02-14",
  "2026-03-29",
  "2026-06-21",
  "2026-08-07",
  "2026-11-30",
];

const out = {
  note:
    "Generated by backend/tools/emit-game-fixtures.ts. Do not hand-edit — " +
    "regenerate it when a generator changes, and expect the Dart mirror test " +
    "to tell you if the rules moved.",
  days: DAYS.map((dayKey) => {
    const q = queens.generate(dayKey);
    const t = tango.generate(dayKey);
    const z = zip.generateWithSolution(dayKey);
    const s = sudoku.generate(dayKey);
    return {
      dayKey,
      queens: { board: q, answer: queens.solve(q) },
      tango: { board: t, answer: tango.solve(t) },
      zip: { board: z.puzzle, answer: z.solution },
      sudoku: { board: s, answer: sudoku.solve(s) },
    };
  }),
};

for (const day of out.days) {
  for (const [game, entry] of Object.entries(day)) {
    if (game === "dayKey") continue;
    const { board, answer } = entry as any;
    if (!answer) throw new Error(`${day.dayKey}/${game}: no answer`);
    const ok =
      game === "queens"
        ? queens.isSolved(board, answer)
        : game === "tango"
        ? tango.isSolved(board, answer)
        : game === "zip"
        ? zip.isSolved(board, answer)
        : sudoku.isSolved(board, answer);
    if (!ok) throw new Error(`${day.dayKey}/${game}: answer fails isSolved`);
  }
}

const path = resolve(__dirname, "../../test/fixtures/daily_games.json");
mkdirSync(dirname(path), { recursive: true });
writeFileSync(path, `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${path} — ${out.days.length} days x 4 games`);
