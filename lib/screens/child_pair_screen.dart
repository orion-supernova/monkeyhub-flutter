/// Pulls the six digits out of whatever the scanner saw. Accepts both the
/// `monkeyhub://pair?c=NNNNNN` URI the parent app renders and a bare code, so
/// a QR generated by an older or newer build still works.
String? extractPairingCode(String raw) {
  final trimmed = raw.trim();
  final uri = Uri.tryParse(trimmed);
  final fromQuery = uri?.queryParameters['c'];
  final candidate = (fromQuery != null && fromQuery.isNotEmpty)
      ? fromQuery
      : trimmed;
  return RegExp(r'^\d{6}$').hasMatch(candidate) ? candidate : null;
}

/// Child-side pairing: scan the parent's QR, or type the six digits.
///
/// Both paths end in the same `redeemPairingCode` call — the scanner is a
/// convenience, never a requirement, so a denied camera or a parent reading
/// numbers down the phone both still work.
class ChildPairScreen extends StatefulWidget {
  const ChildPairScreen({super.key, required this.auth, this.onCancel});

  final AuthService auth;

  /// Shown as a back affordance when this screen was pushed from the adult
  /// login form. Null on a device already marked as a child device, where
  /// there is nothing to go back to.
  final VoidCallback? onCancel;

  @override
  State<ChildPairScreen> createState() => _ChildPairScreenState();
}

class _ChildPairScreenState extends State<ChildPairScreen> {
  final _manual = TextEditingController();
  MobileScannerController? _scanner;

  bool _scanning = false;
  bool _busy = false;
  String? _error;

  /// Guards against the scanner firing the same code repeatedly while the
  /// redeem call is in flight — codes are single-use, so a double submit
  /// would fail the second attempt and show a bogus error.
  bool _consumed = false;

  @override
  void dispose() {
    _manual.dispose();
    _scanner?.dispose();
    super.dispose();
  }

  Future<void> _startScanning() async {
    setState(() {
      _error = null;
      _scanning = true;
      _consumed = false;
      _scanner = MobileScannerController(
        detectionSpeed: DetectionSpeed.noDuplicates,
        formats: const [BarcodeFormat.qrCode],
      );
    });
  }

  void _stopScanning() {
    _scanner?.dispose();
    setState(() {
      _scanner = null;
      _scanning = false;
    });
  }

  void _onDetect(BarcodeCapture capture) {
    if (_consumed || _busy) return;
    for (final barcode in capture.barcodes) {
      final raw = barcode.rawValue;
      if (raw == null) continue;
      final code = extractPairingCode(raw);
      if (code == null) continue;
      _consumed = true;
      HapticFeedback.mediumImpact();
      _stopScanning();
      _submit(code);
      return;
    }
  }

  Future<void> _submit(String code) async {
    if (_busy) return;
    setState(() {
      _busy = true;
      _error = null;
    });
    try {
      await widget.auth.redeemPairingCode(code);
      // On success the app's auth listener swaps this screen out for the home
      // shell — nothing more to do here.
    } catch (e) {
      if (!mounted) return;
      setState(() {
        _error = _humanize(e);
        _consumed = false;
      });
    } finally {
      if (mounted) setState(() => _busy = false);
    }
  }

  /// Never surfaces a raw exception — this screen is read by children.
  ///
  /// No username is typed here, so the shared USER_NOT_FOUND copy ("no account
  /// with that username") would make no sense: on this screen it means the
  /// child's account was deleted out from under the handset.
  String _humanize(Object e) {
    final l10n = AppLocalizations.of(context);
    return humanizeAuthError(
      e,
      l10n,
      fallback: l10n.childPairScreenGenericError,
      overrides: {'USER_NOT_FOUND': l10n.childPairScreenAccountGoneError},
    );
  }

  @override
  Widget build(BuildContext context) {
    final theme = ThemeScope.of(context);
    return Scaffold(
      backgroundColor: Colors.transparent,
      body: DismissKeyboardOnTap(
        child: Stack(
          children: [
            theme.backgroundLayer(context),
            SafeArea(
              child: Center(
                child: ConstrainedBox(
                  constraints: const BoxConstraints(maxWidth: ContentWidth.auth),
                  child: SingleChildScrollView(
                    padding: const EdgeInsets.fromLTRB(20, 36, 20, 24),
                    child: Column(
                      crossAxisAlignment: CrossAxisAlignment.stretch,
                      children: [
                        Text(
                          AppLocalizations.of(context).childPairTitleIos,
                          style: theme.displayLarge.copyWith(letterSpacing: 0.37),
                        ),
                        const SizedBox(height: 8),
                        Text(
                          AppLocalizations.of(context).childPairScreenIntro,
                          style: theme.bodySoft.copyWith(fontSize: 17),
                        ),
                        const SizedBox(height: 28),
                        if (_scanning)
                          _ScannerPanel(
                            controller: _scanner!,
                            onDetect: _onDetect,
                            onCancel: _stopScanning,
                          )
                        else
                          _ScanButton(onTap: _startScanning),
                        const SizedBox(height: 22),
                        Row(
                          children: [
                            Expanded(child: Container(height: 1, color: theme.divider)),
                            Padding(
                              padding: const EdgeInsets.symmetric(horizontal: 12),
                              child: Text(
                                AppLocalizations.of(context)
                                    .childPairScreenOrDivider,
                                style: theme.bodySoft.copyWith(
                                  fontSize: 13,
                                  color: theme.inkMuted,
                                ),
                              ),
                            ),
                            Expanded(child: Container(height: 1, color: theme.divider)),
                          ],
                        ),
                        const SizedBox(height: 22),
                        CodeField(
                          controller: _manual,
                          onCompleted: _submit,
                          enabled: !_busy,
                        ),
                        if (_error != null) ...[
                          const SizedBox(height: 16),
                          Container(
                            padding: const EdgeInsets.fromLTRB(14, 10, 14, 10),
                            decoration: BoxDecoration(
                              color: theme.danger.withValues(alpha: 0.12),
                              borderRadius: BorderRadius.circular(
                                groupedRadius(theme) * 0.6,
                              ),
                            ),
                            child: Text(
                              _error!,
                              style: theme.body.copyWith(color: theme.danger),
                            ),
                          ),
                        ],
                        const SizedBox(height: 22),
                        ProminentButton(
                          label: sentenceCaseOf(
                            context,
                            AppLocalizations.of(context)
                                .childPairScreenSubmitButtonLabel,
                          ),
                          busy: _busy,
                          onTap: _busy
                              ? null
                              : () => _submit(_manual.text.trim()),
                        ),
                        if (widget.onCancel != null) ...[
                          const SizedBox(height: 16),
                          Center(
                            child: GestureDetector(
                              onTap: widget.onCancel,
                              child: Text(
                                AppLocalizations.of(context).childPairBackIos,
                                style: theme.body.copyWith(
                                  fontSize: 15,
                                  color: theme.accent,
                                ),
                              ),
                            ),
                          ),
                        ],
                      ],
                    ),
                  ),
                ),
              ),
            ),
          ],
        ),
      ),
    );
  }
}

class _ScanButton extends StatelessWidget {
  const _ScanButton({required this.onTap});
  final VoidCallback onTap;

  @override
  Widget build(BuildContext context) {
    final theme = ThemeScope.of(context);
    return GestureDetector(
      onTap: onTap,
      behavior: HitTestBehavior.opaque,
      // A big tinted tile, the way the iOS camera-scan affordances look.
      child: Container(
        padding: const EdgeInsets.symmetric(vertical: 26),
        decoration: BoxDecoration(
          color: quietFill(theme),
          borderRadius: BorderRadius.circular(groupedRadius(theme)),
        ),
        child: Column(
          children: [
            Icon(CupertinoIcons.qrcode_viewfinder, size: 34, color: theme.accent),
            const SizedBox(height: 10),
            Text(
              sentenceCaseOf(
                context,
                AppLocalizations.of(context).childPairScreenScanButtonLabel,
              ),
              style: theme.bodyEmph.copyWith(color: theme.accent),
            ),
          ],
        ),
      ),
    );
  }
}

class _ScannerPanel extends StatelessWidget {
  const _ScannerPanel({
    required this.controller,
    required this.onDetect,
    required this.onCancel,
  });

  final MobileScannerController controller;
  final void Function(BarcodeCapture) onDetect;
  final VoidCallback onCancel;

  @override
  Widget build(BuildContext context) {
    final theme = ThemeScope.of(context);
    return Column(
      children: [
        ClipRRect(
          borderRadius: BorderRadius.circular(groupedRadius(theme)),
          child: SizedBox(
            height: 260,
            child: MobileScanner(
              controller: controller,
              onDetect: onDetect,
              // A denied or missing camera must not dead-end the child —
              // the typed path below still works.
              errorBuilder: (context, error) => Container(
                color: theme.surfaceSunken,
                alignment: Alignment.center,
                padding: const EdgeInsets.all(24),
                child: Text(
                  AppLocalizations.of(context)
                      .childPairScreenNoCameraMessage,
                  style: theme.bodySoft,
                  textAlign: TextAlign.center,
                ),
              ),
            ),
          ),
        ),
        const SizedBox(height: 12),
        GestureDetector(
          onTap: onCancel,
          child: Text(
            sentenceCaseOf(
              context,
              AppLocalizations.of(context).childPairScreenStopScanning,
            ),
            style: theme.body.copyWith(fontSize: 15, color: theme.accent),
          ),
        ),
      ],
    );
  }
}
