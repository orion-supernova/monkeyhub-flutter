// Which sounds Jungle Fist should play for a frame: pure logic, no audio engine.
//
// [FightSoundPlanner] reads a [FightState] and returns the cues that are new
// since the last call; [FightAudioDirector] adds the gates (muted, a call is
// live) and voice limiting, then hands the survivors to a [SoundSink]. The real
// sink (flutter_soloud) lives in fight_audio.dart; tests use a fake one, so none
// of this needs the native engine.
import 'dart:math' as math;

import '../core/core.dart';

/// Every sound effect and jingle. [file] is the asset name under
/// assets/audio/fight/ (generated by tool/generate_fight_audio.py).
enum Sfx {
  hitLight('hit_light'),
  hitHeavy('hit_heavy'),
  hitCounter('hit_counter'),
  block('block'),
  perfectBlock('perfect_block'),
  throwHit('throw'),
  whooshLight('whoosh_light'),
  whooshHeavy('whoosh_heavy'),
  projectileFire('projectile_fire'),
  projectileHit('projectile_hit'),
  clash('clash'),
  land('land'),
  roll('roll'),
  dash('dash'),
  superFlash('super_flash'),
  ko('ko'),
  roundStart('round_start'),
  roundFight('round_fight'),
  victory('victory'),
  defeat('defeat'),
  uiTick('ui_tick'),
  uiConfirm('ui_confirm');

  const Sfx(this.file);
  final String file;

  /// Higher wins when a frame has more cues than the voice budget.
  int get priority => switch (this) {
    Sfx.ko || Sfx.victory || Sfx.defeat || Sfx.roundStart || Sfx.roundFight || Sfx.superFlash => 5,
    Sfx.hitCounter || Sfx.hitHeavy || Sfx.throwHit || Sfx.perfectBlock || Sfx.clash => 4,
    Sfx.hitLight || Sfx.block || Sfx.projectileHit || Sfx.projectileFire => 3,
    Sfx.whooshHeavy || Sfx.whooshLight || Sfx.dash || Sfx.roll => 2,
    _ => 1,
  };

  /// Minimum frames between two plays of the same sound, so a flurry of
  /// identical hits cannot stack into a wall of one sample.
  int get minGapFrames => switch (this) {
    Sfx.land || Sfx.dash || Sfx.roll => 6,
    Sfx.whooshLight || Sfx.whooshHeavy => 4,
    Sfx.hitLight || Sfx.block => 2,
    _ => 1,
  };

  /// Pitch variation applies to impacts; jingles and callouts must stay in tune.
  bool get varies => switch (this) {
    Sfx.roundStart || Sfx.roundFight || Sfx.victory || Sfx.defeat || Sfx.uiTick || Sfx.uiConfirm || Sfx.ko => false,
    _ => true,
  };
}

/// One thing to play: which sound, where in the stereo field (-1..1), how loud
/// (0..1) and at what playback speed (1.0 = as recorded).
class SoundCue {
  const SoundCue(this.sfx, {this.pan = 0, this.volume = 1, this.speed = 1});
  final Sfx sfx;
  final double pan, volume, speed;

  @override
  String toString() => 'SoundCue(${sfx.name}, pan ${pan.toStringAsFixed(2)}, vol ${volume.toStringAsFixed(2)})';
}

/// Stage x (fixed-point units, 0..[stageWidth]) to a stereo pan, -0.7..0.7.
double panForX(int x) => ((x / stageWidth) * 2 - 1).clamp(-1.0, 1.0) * 0.7;

class FightSoundPlanner {
  FightSoundPlanner({math.Random? random}) : _rng = random ?? math.Random();
  final math.Random _rng;

  /// Events and derived cues already turned into sound, keyed by what they
  /// are. Rollback re-simulates frames and re-emits the same event (same
  /// frame, kind, player, x): the key makes the second one a no-op.
  final Set<String> _done = {};
  int _lastFrame = -1;
  List<(int owner, int x, int y)> _prevProjectiles = const [];

  /// Events older than this many frames at the moment we first see them are
  /// not worth playing (a screen that was backgrounded, a late subscriber).
  static const staleFrames = 8;

  /// How long dedup keys are kept; far longer than any rollback window.
  static const keepFrames = 180;

  /// A frame counter that jumps back further than this is a new match.
  static const restartGap = 30;

  /// Heavy-hit damage threshold. Light normals deal 30, heavies 60 to 70
  /// (before combo scaling), so this splits them with room for scaling.
  static const heavyDamage = 45;

  void reset() {
    _done.clear();
    _lastFrame = -1;
    _prevProjectiles = const [];
  }

  /// Cues that are new in [s]. Call once per rendered/stepped frame; calling
  /// again with the same (or a rolled-back) state returns nothing new.
  List<SoundCue> plan(FightState s, {required int localPlayer}) {
    // A new match restarts the frame counter: forget everything we have seen.
    // Rollback only ever rewinds a handful of frames, never this many.
    if (_lastFrame >= 0 && s.frame < _lastFrame - restartGap) {
      _done.clear();
      _prevProjectiles = const [];
    }
    final out = <SoundCue>[];

    bool fresh(String key) => _done.add(key);

    // Phase callouts. Keyed by round so a rollback across the boundary does
    // not repeat them.
    if (s.phase == Phase.intro && fresh('start:${s.round}')) {
      out.add(const SoundCue(Sfx.roundStart, volume: 0.9));
    }
    if (s.phase == Phase.fight && fresh('fight:${s.round}')) {
      out.add(const SoundCue(Sfx.roundFight));
    }
    if (s.phase == Phase.over && fresh('over')) {
      final w = s.matchWinner;
      if (w == localPlayer) {
        out.add(const SoundCue(Sfx.victory));
      } else if (w == 0 || w == 1) {
        out.add(const SoundCue(Sfx.defeat));
      }
    }

    // Engine events.
    for (final e in s.events) {
      if (e.frame < s.frame - staleFrames && !_done.contains(_eventKey(e))) {
        _done.add(_eventKey(e));
        continue;
      }
      if (!fresh(_eventKey(e))) continue;
      final cue = _cueFor(e, s);
      if (cue != null) out.add(cue);
    }

    // Swing whooshes: a fighter entering a move (move frame 1).
    for (var i = 0; i < 2; i++) {
      final f = s.p[i];
      if (f.state != St.move || f.sf != 1) continue;
      if (!fresh('swing:${s.frame}:$i:${f.serial}')) continue;
      final moves = s.chars[i].moves;
      if (f.moveId < 0 || f.moveId >= moves.length) continue;
      final cue = _whooshFor(moves[f.moveId], f.x);
      if (cue != null) out.add(cue);
    }

    _prevProjectiles = [for (final p in s.projectiles) (p.owner, p.x, p.y)];
    _lastFrame = s.frame;
    if (_done.length > 600) _prune(s.frame);
    return out;
  }

  String _eventKey(FightEvent e) => 'ev:${e.frame}:${e.kind}:${e.player}:${e.x}';

  void _prune(int frame) {
    final floor = frame - keepFrames;
    _done.removeWhere((k) {
      final parts = k.split(':');
      if (parts.length < 2) return false;
      final f = int.tryParse(parts[1]);
      return f != null && (parts[0] == 'ev' || parts[0] == 'swing') && f < floor;
    });
  }

  double _jitter(Sfx sfx) => sfx.varies ? 1 + (_rng.nextDouble() * 2 - 1) * 0.04 : 1;

  SoundCue _cue(Sfx sfx, int x, {double volume = 1, double speed = 1}) =>
      SoundCue(sfx, pan: panForX(x), volume: volume, speed: speed * _jitter(sfx));

  /// Did a projectile owned by [owner] just vanish near ([x], [y])? Then the
  /// contact event is a fireball bursting, not a fist landing.
  bool _projectileContact(FightState s, int owner, int x, int y) {
    var before = 0, after = 0, near = false;
    for (final p in _prevProjectiles) {
      if (p.$1 != owner) continue;
      before++;
      if ((p.$2 - x).abs() < 6000 && (p.$3 - y).abs() < 12000) near = true;
    }
    for (final p in s.projectiles) {
      if (p.owner == owner) after++;
    }
    return near && after < before;
  }

  SoundCue? _cueFor(FightEvent e, FightState s) {
    switch (e.kind) {
      case Ev.hit:
        if (_projectileContact(s, e.player, e.x, e.y)) return _cue(Sfx.projectileHit, e.x);
        return e.value >= heavyDamage ? _cue(Sfx.hitHeavy, e.x) : _cue(Sfx.hitLight, e.x);
      case Ev.counterHit:
        return _cue(Sfx.hitCounter, e.x);
      case Ev.block:
        // [player] of a block event is the defender; the attacker is the other.
        if (_projectileContact(s, 1 - e.player, e.x, e.y)) return _cue(Sfx.projectileHit, e.x, volume: 0.7);
        return _cue(Sfx.block, e.x);
      case Ev.perfectBlock:
        return _cue(Sfx.perfectBlock, e.x);
      case Ev.throwHit:
        return _cue(Sfx.throwHit, e.x);
      case Ev.throwTech:
        return _cue(Sfx.clash, e.x, volume: 0.75, speed: 1.12);
      case Ev.ko:
        return _cue(Sfx.ko, e.x);
      case Ev.projectileSpawn:
        return _cue(Sfx.projectileFire, e.x, volume: 0.85);
      case Ev.superFlash:
        return const SoundCue(Sfx.superFlash);
      case Ev.wallBounce:
        return _cue(Sfx.hitHeavy, e.x, volume: 0.8, speed: 0.82);
      case Ev.groundBounce:
        return _cue(Sfx.land, e.x, volume: 1, speed: 0.85);
      case Ev.land:
        return _cue(Sfx.land, e.x, volume: 0.55);
      case Ev.roll:
        return _cue(Sfx.roll, e.x, volume: 0.8);
      case Ev.dash:
        return _cue(Sfx.dash, e.x, volume: 0.7, speed: e.value < 0 ? 0.9 : 1);
      case Ev.clash:
        return _cue(Sfx.clash, e.x);
      case Ev.armor:
        return _cue(Sfx.block, e.x, volume: 0.9, speed: 0.8);
      case Ev.counterTrigger:
        return _cue(Sfx.perfectBlock, e.x, volume: 0.7, speed: 0.9);
      default:
        return null; // trap, roundEnd: covered by their own hit / KO events
    }
  }

  SoundCue? _whooshFor(MoveDef m, int x) {
    if (m.grab || m.cls == MoveClass.system) return null; // the throw sound is on contact
    // Pure projectile launches already get the energy-release sound.
    if (m.windows.isEmpty && m.projectiles.isNotEmpty) return null;
    final heavy = m.cls != MoveClass.normal || m.name.contains('Heavy') || m.name.contains('Finisher');
    return heavy ? _cue(Sfx.whooshHeavy, x, volume: 0.8) : _cue(Sfx.whooshLight, x, volume: 0.7);
  }
}

/// Plays a cue. Implemented by the flutter_soloud engine and by test fakes.
abstract class SoundSink {
  void play(SoundCue cue);
}

/// Planner + gates + voice limiting. [sink] receives only what should be heard.
class FightAudioDirector {
  FightAudioDirector({
    required this.sink,
    required this.soundOn,
    required this.callActive,
    FightSoundPlanner? planner,
    this.maxPerFrame = 4,
  }) : planner = planner ?? FightSoundPlanner();

  final SoundSink sink;
  final bool Function() soundOn;
  final bool Function() callActive;
  final FightSoundPlanner planner;

  /// Most cues one frame may start: a long combo or a super lands several
  /// events at once and would otherwise clip into mush.
  final int maxPerFrame;

  final Map<Sfx, int> _lastPlayed = {};

  bool get audible => soundOn() && !callActive();

  /// Run one frame. Returns what was played (handy for tests).
  List<SoundCue> onFrame(FightState s, {required int localPlayer}) {
    // Keep the planner's memory current even while silent, so unmuting
    // mid-fight does not replay the last second.
    final cues = planner.plan(s, localPlayer: localPlayer);
    if (!audible || cues.isEmpty) return const [];
    final eligible = <SoundCue>[
      for (final c in cues)
        if (s.frame - (_lastPlayed[c.sfx] ?? -1000) >= c.sfx.minGapFrames || s.frame < (_lastPlayed[c.sfx] ?? -1000)) c,
    ];
    eligible.sort((a, b) => b.sfx.priority.compareTo(a.sfx.priority));
    final played = eligible.take(maxPerFrame).toList();
    for (final c in played) {
      _lastPlayed[c.sfx] = s.frame;
      sink.play(c);
    }
    return played;
  }

  /// UI sounds are not tied to a frame and obey the same gates.
  bool ui(Sfx sfx) {
    if (!audible) return false;
    sink.play(SoundCue(sfx, volume: 0.8));
    return true;
  }

  void reset() {
    planner.reset();
    _lastPlayed.clear();
  }
}
